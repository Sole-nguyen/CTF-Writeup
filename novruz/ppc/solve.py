def coef_expr(x: float) -> str:
    if x >= 0:
        return repr(x)
    return f"(0-{repr(abs(x))})"


def build_expr() -> str:
    terms = [f"({coef_expr(coef)}/(a-({i}.5)))" for i, coef in enumerate(COEFFS)]
    return "+".join(terms)


def recv_until_newline(sock: socket.socket) -> bytes:
    data = b""
    while b"\n" not in data:
        chunk = sock.recv(4096)
        if not chunk:
            break
        data += chunk
    return data


def main() -> None:
    expr = build_expr()

    with socket.create_connection((HOST, PORT), timeout=20) as sock:
        banner = recv_until_newline(sock)
        if banner:
            print(banner.decode(errors="replace").rstrip())

        sock.sendall(expr.encode() + b"\n")

        out = b""
        while True:
            chunk = sock.recv(4096)
            if not chunk:
                break
            out += chunk

    text = out.decode(errors="replace").strip()
    if text:
        print(text)


if __name__ == "__main__":
    main()
